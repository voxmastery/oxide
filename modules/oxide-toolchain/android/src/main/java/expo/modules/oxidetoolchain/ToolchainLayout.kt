package expo.modules.oxidetoolchain

import android.content.Context
import android.os.Build
import java.io.File

/**
 * Where everything lives on the phone.
 *
 * Executables (Android 10+ only executes files from the APK's native library dir):
 *   <nativeLibraryDir>/librustc.so, libcargo.so, librust-lld.so, libclippy-driver.so,
 *   librustfmt.so, librustc_driver-*.so, libLLVM*.so, libc++_shared.so, libz.so…
 *   <nativeLibraryDir>/liboxide-rustc.so   adds --sysroot (see toolchain/native/oxide-rustc.c)
 *   <nativeLibraryDir>/liboxide-cc.so      cc for build scripts / proc-macros (oxide-cc.c)
 *   <nativeLibraryDir>/liboxide-exec.so    LD_PRELOAD exec shim for build scripts (oxide-exec.c)
 *
 * Data (unpacked by install() into filesDir, never executed):
 *   files/toolchain/rust          rustc sysroot: lib/rustlib/{wasm32-wasip1-threads,aarch64-linux-android}/lib
 *   files/toolchain/vendor        vendored crates (rand, tokio and their dependencies)
 *   files/toolchain/android-link  NDK crt objects and libc stubs for oxide-cc
 *   files/toolchain/cargo-home    CARGO_HOME; config.toml is regenerated on every start
 *   files/toolchain/installed.json
 *   files/home                    the Terminal's ~ (Paths.document + "home" on the JS side)
 */
class ToolchainLayout(context: Context) {
  val nativeLibDir = File(context.applicationInfo.nativeLibraryDir)
  val filesDir: File = context.filesDir
  val cacheDir: File = context.cacheDir
  val toolchainDir = File(filesDir, "toolchain")
  val sysroot = File(toolchainDir, "rust")
  val vendorDir = File(toolchainDir, "vendor")
  val linkKit = File(toolchainDir, "android-link")
  val cargoHome = File(toolchainDir, "cargo-home")
  val installedMarker = File(toolchainDir, "installed.json")
  val home = File(filesDir, "home")
  val downloadDir = File(cacheDir, "oxide-payload")

  /** Tool name as typed → file in nativeLibraryDir. */
  fun tool(name: String): File? {
    // Android's own shell and toybox tools are system programs: apps may run them.
    if (name == "sh") return File("/system/bin/sh")
    val file = when (name) {
      "cargo" -> "libcargo.so"
      // Always go through the sysroot wrapper.
      "rustc" -> "liboxide-rustc.so"
      "rustc-real" -> "librustc.so"
      "rustfmt" -> "librustfmt.so"
      "rust-lld" -> "librust-lld.so"
      "clippy-driver" -> "libclippy-driver.so"
      "rustdoc" -> "librustdoc.so"
      else -> return null
    }
    return File(nativeLibDir, file)
  }

  val is64BitArm: Boolean
    get() = Build.SUPPORTED_ABIS.firstOrNull() == "arm64-v8a"

  val nativeToolsPresent: Boolean
    get() = File(nativeLibDir, "libcargo.so").isFile &&
      File(nativeLibDir, "librustc.so").isFile &&
      File(nativeLibDir, "liboxide-rustc.so").isFile &&
      File(nativeLibDir, "librust-lld.so").isFile

  /**
   * The WebAssembly target of the installed payload: wasm32-wasip1-threads for payloads built
   * with toolchain/build-android-host.sh, wasm32-wasip1 for the Termux repackaging (Termux does
   * not ship std for the threads target).
   */
  val wasmTarget: String
    get() = try {
      org.json.JSONObject(installedMarker.readText()).optString("target").ifEmpty { WASM_TARGET }
    } catch (_: Exception) {
      WASM_TARGET
    }

  val dataInstalled: Boolean
    get() = installedMarker.isFile && File(sysroot, "lib/rustlib/$wasmTarget/lib").isDirectory

  /** Environment for every host tool. The JS side adds per-command variables on top. */
  fun baseEnv(): Map<String, String> {
    val nld = nativeLibDir.absolutePath
    return linkedMapOf(
      "HOME" to home.absolutePath,
      "PATH" to "/system/bin",
      "TMPDIR" to cacheDir.absolutePath,
      "LD_LIBRARY_PATH" to nld,
      "CARGO_HOME" to cargoHome.absolutePath,
      "RUSTC" to File(nativeLibDir, "liboxide-rustc.so").absolutePath,
      "RUSTDOC" to File(nativeLibDir, "librustdoc.so").absolutePath,
      "RUSTFMT" to File(nativeLibDir, "librustfmt.so").absolutePath,
      "CARGO_TERM_COLOR" to "always",
      "CARGO_TERM_PROGRESS_WHEN" to "never",
      "TERM" to "xterm-256color",
      "OXIDE_NLD" to nld,
      "OXIDE_SYSROOT" to sysroot.absolutePath,
      "OXIDE_LINKKIT" to linkKit.absolutePath,
      "OXIDE_EXEC_ONLY" to filesDir.absolutePath,
    )
  }

  /**
   * $CARGO_HOME/config.toml. The native library dir contains a random component that changes
   * whenever the app is updated, so this is rewritten on every start.
   */
  /**
   * Online: cargo uses crates.io (cargo add / cargo install / any dependency), caching downloads
   * in CARGO_HOME. Offline: cargo resolves only from the vendored crates in the payload.
   */
  @Volatile var online: Boolean = false

  fun writeCargoConfig(online: Boolean = this.online) {
    this.online = online
    cargoHome.mkdirs()
    val nld = nativeLibDir.absolutePath
    val target = wasmTarget
    val text = """
      |# Generated by Oxide on every app start. Do not edit: changes are overwritten.
      |# User programs are compiled to WebAssembly and run in-process (Android forbids
      |# executing files the app writes). Build scripts and proc-macros are compiled for the
      |# phone itself (aarch64-linux-android) and linked with Oxide's cc.
      |
      |[build]
      |target = "$target"
      |
      |[target.$target]
      |linker = ${toml("$nld/librust-lld.so")}
      |# tokio (Rustlings' async1) only builds for wasm with tokio_unstable; its
      |# multi-threaded runtime then works on wasm32-wasip1-threads.
      |rustflags = ["--cfg", "tokio_unstable"]
      |
      |[target.$HOST_TARGET]
      |linker = ${toml("$nld/liboxide-cc.so")}
      |
      |${if (online) "" else "[source.crates-io]\n      |replace-with = \"oxide-vendored\"\n      |\n      |[source.oxide-vendored]\n      |directory = ${toml(vendorDir.absolutePath)}\n      |"}
      |[net]
      |offline = ${!online}
      |git-fetch-with-cli = false
      |
      |[http]
      |# Android's system CA certificates, combined into one PEM file.
      |cainfo = ${toml(caBundle().absolutePath)}
      |
      |[term]
      |color = "always"
      |
      |[cargo-new]
      |vcs = "none"
      |""".trimMargin()
    val file = File(cargoHome, "config.toml")
    if (!file.isFile || file.readText() != text) file.writeText(text)
  }

  /** Concatenate Android's system CA certificates into one PEM file for cargo's HTTP client. */
  private fun caBundle(): File {
    val out = File(cargoHome, "cacert.pem")
    if (out.isFile && out.length() > 0) return out
    val dir = File("/system/etc/security/cacerts")
    val sb = StringBuilder()
    dir.listFiles()?.sortedBy { it.name }?.forEach { f ->
      val text = runCatching { f.readText() }.getOrNull() ?: return@forEach
      val begin = text.indexOf("-----BEGIN CERTIFICATE-----")
      val end = text.indexOf("-----END CERTIFICATE-----")
      if (begin >= 0 && end > begin) sb.append(text, begin, end + 25).append('\n')
    }
    out.writeText(sb.toString())
    return out
  }

  private fun toml(s: String): String = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

  companion object {
    /** Default WebAssembly target. See toolchain/README.md, "Threads". */
    const val WASM_TARGET = "wasm32-wasip1-threads"
    const val HOST_TARGET = "aarch64-linux-android"
  }
}
