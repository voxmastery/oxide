#!/usr/bin/env node
// Writes src/features/buildalong/data.ts from scripts/buildalong/<project>/ (meta.json, starter/,
// tests/). Reference solutions (scripts/buildalong-solutions/) are never read here, so they stay
// out of the app bundle.
//
//   node scripts/buildalong/build.mjs        then   node scripts/buildalong/verify.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { cargoToml, projectNames, readProject } from './lib.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, '../../src/features/buildalong/data.ts');
const TEST_FILE = 'tests/milestones.rs';

const projects = projectNames().map((name) => {
  const { meta, starter, tests } = readProject(name);
  const testSrc = tests[TEST_FILE];
  if (!testSrc) throw new Error(`${name}: missing ${TEST_FILE}`);
  const names = [...testSrc.matchAll(/#\[test\]\s*\n\s*fn (\w+)\s*\(/g)].map((m) => m[1]);
  const milestones = meta.milestones.map((m) => {
    const t = names.filter((n) => n.startsWith(m.id + '_'));
    if (!t.length) throw new Error(`${name}: milestone ${m.id} has no tests`);
    return { ...m, filter: m.id + '_', tests: t };
  });
  const stray = names.filter((n) => !milestones.some((m) => n.startsWith(m.filter)));
  if (stray.length) throw new Error(`${name}: tests outside any milestone: ${stray.join(', ')}`);
  const { smoke, milestones: _m, ...rest } = meta;
  void smoke;
  void _m;
  return {
    name,
    ...rest,
    testFile: TEST_FILE,
    files: { 'Cargo.toml': cargoToml(name), '.gitignore': '/target\n', ...starter, ...tests },
    milestones,
  };
});

const body = `// Generated by scripts/buildalong/build.mjs from scripts/buildalong/. Do not edit by hand.
// Starter files and milestone tests only; the reference solutions are not part of the app.
import type { BuildAlongProject } from './types';

export const PROJECTS: BuildAlongProject[] = ${JSON.stringify(projects, null, 2)};
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${projects.map((p) => `${p.name} (${p.milestones.length})`).join(', ')}`);
